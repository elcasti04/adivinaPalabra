const pista = document.getElementById('pista')
const palabrah2 = document.getElementById('palabra')
const userPalabra = document.getElementById('userPalabra')
const comprobar = document.getElementById('comprobar')
const anuncio = document.getElementById('anuncio')
const continuar = document.getElementById('btn-continuar')
const puntos = document.getElementById('puntos')
const cant = document.getElementById('cant')

let points = 0
let palabraObjetivo = ''


function iniciar () {
    
const seleccionador = Math.floor(Math.random() * Palabras.length)

const newPal = Palabras[seleccionador]
palabraObjetivo = newPal.palabra.toUpperCase()

function verEspacios () {
    const spaces = palabraObjetivo.length
    puntos.innerText = points
    palabrah2.innerText = '_ '.repeat(spaces)
    pista.innerText = newPal.pista
    cant.innerText = newPal.palabra.length

}

verEspacios()

}

function comprobarRespuesta () {
const usuario = userPalabra.value.trim().toUpperCase();

  if (usuario === palabraObjetivo) {
    palabrah2.innerText = palabraObjetivo;
    anuncio.innerText = 'GANASTE'
    points+=1
    continuar.innerText = 'Siguiente'
    comprobar.disabled = true

    continuar.addEventListener('click', () => {
        iniciar()
        continuar.innerText = ''
        anuncio.innerText = ''
        comprobar.disabled = false
    })

  } else {
    anuncio.innerText = 'SIGUE INTENTANDO'
  }
  userPalabra.value = "";
  puntos.innerText = points
  
}

comprobar.addEventListener('click', comprobarRespuesta)

iniciar()